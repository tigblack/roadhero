def pad_track(pc, chords, bar0=1, vel=70, voicing=PAD_V, levels=None):
    """Sustained chords; equal neighbours are tied into one long chord."""
    i = 0
    while i < len(chords):
        j = i
        while j + 1 < len(chords) and chords[j + 1] == chords[i]:
            j += 1
        if chords[i] is not None:
            v = vel if levels is None else levels[i]
            pc.chord('pad', bar0 + i, 0, chords[i], (j - i + 1) * 16, v, gate=1.0, voicing=voicing[chords[i]])
        i = j + 1


def harmony_list(chords, bar0=1):
    """Symbols for review: the colours the parts really sound over each root (the riff's sixth and the lead's ninth
    over D, the pad's major seventh over C, the riff's flat seventh over Em)."""
    sym = {'Em': 'Em7', 'C': 'Cmaj13', 'Cmaj7': 'Cmaj9', 'D': 'D6/9', 'G': 'Gmaj9', 'Am': 'Am7', 'Am7': 'Am7'}
    return [{'bar': bar0 + i, 'beat': 0, 'symbol': sym.get(c, c)} for i, c in enumerate(chords)]


