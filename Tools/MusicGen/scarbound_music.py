"""Scarbound background music, written note by note for the music-production skill's renderer.

    python scarbound_music.py <piece> <out_dir>
    piece: sketch1 | sketch2 | sketch3 | theme

Writes <out_dir>/song.json (schema music-production/v1). Render it with make_music.sh (or the skill's
`studio.py render`). Every note, velocity, slide and mix setting is in this file; nothing is generated by a model.

Musical frame shared by every piece
- 100 BPM, 4/4. One bar = 2.4 s, so 48 bars = 115.2 s = 5,080,320 samples at 44.1 kHz (an exact integer).
- Home key E minor (Aeolian, pentatonic-led). Only the seven pitch classes of G major are used (no C#, no D#), so the
  G-major upgrade / unlock fanfares (Tools/AudioGen/gen_audio.py: casual_levelup, casual_unlock) always land on
  consonant ground when they play over the ducked music.
- The A cycle: Em | Em | C | D  (i - i - bVI - bVII). D -> Em closes every cycle and the loop seam.
- The riff: a baritone-register guitar (E2-D3) on an open E drone, a quick three-note rise into beat 2
  ("da . . da-da-DAA"), then space for the drums and the motif.
- The motif ("Scarbound call"): two 16th pickups into a held, slid-into high note, then a fall home:
  B4 D5 | E5 . D5 | B4 . . A4 G4 | E4 ..  -- it starts on beat 3-and, i.e. inside the riff's space.
"""
