def shaker16(base=1.0):
    out = []
    for s in range(16):
        v = 70 if s % 4 == 2 else 56 if s % 4 == 0 else 38
        out.append((s, CABASA, v * base))
    return out


def hats8(a=44, b=34, ghosts=False, open_end=False):
    out = [(s, HAT, a if s % 4 == 0 else b) for s in range(0, 16, 2)]
    if ghosts:
        out += [(7, HAT, 22), (15, HAT, 22)]
    if open_end:
        out = [h for h in out if h[0] != 14] + [(14, OHAT, 54)]
    return out


