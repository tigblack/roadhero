def P(x):
    return pitch_of(x, 'score') if isinstance(x, str) else int(x)


G_MAJOR_PCS = {0, 2, 4, 6, 7, 9, 11}   # the only pitch classes in the music (E minor = G major's notes)


def diatonic_below(p):
    """The scale step under pitch p (a whole or half step down, inside G major)."""
    q = p - 1
    while q % 12 not in G_MAJOR_PCS:
        q -= 1
    return q


def diatonic_above(p):
    q = p + 1
    while q % 12 not in G_MAJOR_PCS:
        q += 1
    return q


def approach(next_root, chord):
    """A step into the next root that makes no minor second / ninth with the pad chord still sounding."""
    held = {P(n) % 12 for n in PAD_V[chord]}
    for q in (diatonic_below(next_root), diatonic_above(next_root)):
        if all((q - h) % 12 not in (1, 11) for h in held):
            return q
    return next_root


class Bend:
    """A part's pitch-wheel curve in absolute beats, in time order (two points on one beat make a jump)."""

    def __init__(self, swing=None):
        self.pts = [[0.0, 0.0]]
        self.swing = swing

    def at(self, t):
        return swung(t, self.swing, 4.0) if self.swing else t

    def _add(self, t, v):
        t = round(t, 6)
        last = self.pts[-1]
        if t < last[0] - 1e-9:
            raise ValueError(f'bend point at {t} before {last[0]}')
        if abs(t - last[0]) < 1e-9 and abs(v - last[1]) < 1e-9:
            return
        self.pts.append([t, round(v, 4)])

    def jump(self, t, v):
        last = self.pts[-1]
        if t > last[0] + 1e-9:
            self._add(t, last[1])
        self._add(t, v)

    def ramp(self, t, v):
        self._add(t, v)

    def slide_in(self, t, semis, beats):
        """The note at written beat t starts `semis` below and slides up over `beats`; begins 15 ms early so the note's
        first frame is already bent whatever its timing deviation."""
        t0 = self.at(t) - 0.025
        self.jump(t0, -semis)
        self.ramp(self.at(t) + beats, 0.0)

    def vibrato(self, t0, t1, depth=0.32, rate_hz=5.4, delay=0.35):
        """Upward vibrato (a string is only ever pushed up) on a held note from written beat t0 to t1."""
        start, end = max(self.at(t0) + delay, self.pts[-1][0]), self.at(t1) - 0.05
        if end - start < 0.2:
            return
        step = (TEMPO / 60.0) / rate_hz / 2.0   # beats per half period
        self.jump(start, 0.0)
        t, up, k = start, True, 0
        while t + step < end:
            t += step
            k += 1
            amp = depth * min(1.0, k / 4.0)        # the vibrato widens over its first two periods
            self.ramp(t, amp if up else 0.0)
            up = not up
        self.ramp(end, 0.0)

    def fall(self, t0, t1, semis=5):
        """Slide down `semis` from written beat t0 to t1 (the end of a note). The wheel stays down until the next
        note of the part resets it (Piece.phrase), so the release tail does not jump back up."""
        self.jump(self.at(t0), 0.0)
        self.ramp(self.at(t1), -semis)

    def reset_before(self, t):
        """Back to 0 just before the note at written beat t, if a fall left the wheel down."""
        if abs(self.pts[-1][1]) > 1e-9:
            self.jump(max(self.at(t) - 0.03, self.pts[-1][0]), 0.0)


class Piece:
    def __init__(self, title, bars, swing, config=CONFIG):
        self.song = Song(title, bars=bars, tempo=TEMPO, tail_seconds=12, config=str(config))
        self.swing = swing
        self.bends = {}
        self.parts = {}

    def part(self, ident, role, instrument=None, mix=None, performance=None, swing=True, **kw):
        perf = dict(performance or {})
        if swing and self.swing:
            perf['swing'] = dict(self.swing)
        p = self.song.part(ident, role, instrument, mix=mix, performance=perf, **kw)
        self.parts[ident] = p
        return p

    def bend(self, ident):
        if ident not in self.bends:
            sw = self.parts[ident].track['performance'].get('swing')
            self.bends[ident] = Bend(sw)
        return self.bends[ident]

    def put(self, ident, bar, step, pitch, steps, vel, gate=None, **fields):
        bar += step // 16
        step %= 16
        bars = self.song.project['clock']['bars']
        steps = min(steps, (bars - bar) * 16 + 16 - step)   # nothing rings past the last bar (the loop folds the tail)
        return self.parts[ident].note(bar, 1 + step / 4, P(pitch), steps / 4,
                                      velocity=int(max(1, min(127, round(vel)))), gate=gate, **fields)

    # ---- writers
    def riff_bar(self, bar, kind, vscale=1.0, ident='riff'):
        for st, p, n, v, g in RIFF[kind]:
            self.put(ident, bar, st, p, n, v * vscale, gate=g, articulation='riff')

    def bass_bar(self, bar, kind, vscale=1.0):
        for st, p, n, v, g in BASS_A[kind]:
            self.put('bass', bar, st, p, n, v * vscale, gate=g)

    def phrase(self, ident, bar0, phrase, vscale=1.0, transpose=0, gate=.92, label='motif'):
        b = self.bend(ident) if any(o for *_, o in phrase) else None
        for boff, st, p, n, v, orn in phrase:
            bar = bar0 + boff + st // 16
            st %= 16
            t = (bar - 1) * 4 + st / 4
            self.put(ident, bar, st, P(p) + transpose, n, v * vscale, gate=gate, phrase=label)
            if b is not None and orn not in ('in1', 'in2', 'in5'):
                b.reset_before(t)
            if orn == 'in2':
                b.slide_in(t, 2, 0.12)
            elif orn == 'in1':
                b.slide_in(t, 1, 0.08)
            elif orn == 'in5':
                b.slide_in(t, 5, 0.4)
            elif orn == 'vib':
                b.vibrato(t, t + n / 4)
            elif orn == 'fall':
                b.fall(t + n / 4 * 0.55, t + n / 4 * 0.95)

    def drums(self, ident, bar, hits):
        kit = {KICK: 2, STICK: 1, SNARE: 2, HAT: 1, PEDAL: 1, OHAT: 2, RIDE: 2, CRASH: 8, CRASH2: 8,
               TOM_HI: 2, TOM_MH: 2, TOM_ML: 2, TOM_LO: 2}
        world = {OCEAN: 16, SHAKER_ROLL: 8, GUIRO_L: 4, GUIRO_S: 2, FINGER_CYM: 8, ANVIL: 6, BRAKE: 4, FRAME_L: 6,
                 FRAME_L_MUTE: 2, FRAME_S: 4, CAJ_BASS: 2, CAJ_SLAP: 2, CAJ_TONE: 2, SLIT_HI: 3, SLIT_LO: 3,
                 CABASA: 1, SHAKER_S: 1, SHAKER_L: 1, CLAVES: 2}
        for st, key, v in hits:
            if ident == 'drums':
                self.put('drums', bar, st, key, kit.get(key, 2), v, gate=.9)
                continue
            part = PERC_PART[key]
            if key in PERC_VEL:
                lo, hi = PERC_VEL[key]
                v = lo + (hi - lo) * min(1.0, max(0.0, (v - 18) / 66.0))
            self.put(part, bar, st, key, world.get(key, 2), v, gate=.9)

    def chord(self, ident, bar, step, names, steps, vel, gate=1.0, voicing=None):
        for p in (voicing or names):
            self.put(ident, bar, step, p, steps, vel, gate=gate)

    def finish(self, path, seed, overrides, extra):
        self.song.project['tracks'] = [t for t in self.song.project['tracks'] if t['notes']]
        for ident, b in self.bends.items():
            t = self.parts[ident].track
            t['performance']['bend'] = b.pts
        self.song.project.update(extra)
        expression.apply(self.song.project, overrides=overrides, seed=seed, drift='time')
        return self.song.save(path)


